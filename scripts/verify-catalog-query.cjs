const fs = require('fs');
const ts = require('typescript');
const assert = require('node:assert/strict');
const loaded = { exports: {} };
new Function('exports', 'module', ts.transpileModule(fs.readFileSync('lib/discovery/catalog-query.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(loaded.exports, loaded);
const { catalogQuery, catalogHref, CATALOG_PAGE_SIZE } = loaded.exports;
assert.equal(CATALOG_PAGE_SIZE, 24);
for (const page of ['-1', '1.5', 'Infinity', '1000000', ['2', '3']]) assert.equal(catalogQuery({ page }).page, 1);
assert.equal(catalogQuery({ page: '0' }).page, 1);
assert.equal(catalogQuery({ page: '999999' }).page, 100000);
assert.deepEqual(catalogQuery({ intent: ['sale','rent'], q: ['a','b'] }), { page:1, intent:'all', q:'', area:'' });
const filters = catalogQuery({ q:'Villa),status.eq.draft,(title.ilike.%_', area:'St. Andrew', intent:'sale', page:'6' });
assert(!/[(),.%_]/.test(filters.q));
assert.equal(filters.area, 'St Andrew');
const url = new URL(catalogHref(filters, 2), 'https://example.com');
assert.equal(url.searchParams.get('q'), filters.q);
assert.equal(url.searchParams.get('area'), filters.area);
assert.equal(url.searchParams.get('intent'), 'sale');
assert.equal(url.searchParams.get('page'), '2');
assert.equal(catalogHref(catalogQuery({}), 1), '/listings');
assert.equal(catalogQuery({q:'é'.repeat(150)}).q.length,120);
console.log('PASS: bounded pagination, repeated query parameters, filter syntax/wildcard isolation and preserved search navigation');
